"""HTTP service around axiom-rules-engine for the cliff explorer.

modal_app.py builds the Modal image and serves ``create_app``. This module
imports without Modal, so tests drive the real request path against either
the real engine binary or a fake one (tests/fake_engine.py).

Two execution paths share the wire shape of ``POST /run`` and
``POST /cliff-sweep``:

1. No parameter overrides → run the prebuilt ``<slug>.compiled.json``
   artifact baked into the image.
2. Parameter overrides → patch the program's rulespec YAMLs *in place*,
   compile, and restore the original bytes, all under a per-program lock;
   then run the compiled artifact outside the lock. Compiled artifacts are
   cached by (program, overrides), so a household edit under an unchanged
   reform skips the compile.

Why in place: the old path copied both rulespec trees (~1,250 files plus
``.git``) into a scratch dir per request. That cost ~1 s on a warm
container and 90 s on a cold one, where Modal lazy-loads each image file on
first read — past Vercel's 60 s function limit, which is the
FUNCTION_INVOCATION_TIMEOUT users saw after moving a slider. Compiling in
place reads only the program's import closure (measured: ~3 s cold, ~50 ms
warm). Restoring from in-memory originals under the lock means every
compile sees exactly its own overrides; tests/test_engine_service.py
checks that under concurrency.

Handlers are plain ``def`` so FastAPI runs them on its threadpool. Under
the old ``async def`` handlers every blocking compile stalled the event
loop, so concurrent requests (``/health`` and cache hits included) queued
behind it.
"""

