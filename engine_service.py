def make_yaml():
    from ruamel.yaml import YAML

    yaml_io = YAML()
    yaml_io.preserve_quotes = True
    yaml_io.indent(mapping=2, sequence=4, offset=2)
    yaml_io.width = 4096
    return yaml_io


def _finite_number(value: Any, what: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise OverrideError(f"{what} must be a finite number, got {value!r}")
    try:
        number = float(value)
    except OverflowError:
        number = math.inf
    if not math.isfinite(number):
        raise OverrideError(f"{what} must be a finite number, got {value!r}")
    return number


def apply_patch(rule: dict[str, Any], patch: Any) -> None:
    """Apply one override patch to a parameter rule's version-0 entry."""
    if not isinstance(patch, dict):
        raise OverrideError(f"patch must be an object, got {patch!r}")
    versions = rule.get("versions") or [None]
    version = versions[0]
    if version is None:
        raise OverrideError(f"parameter {rule.get('name')} has no versions")
    kind = patch.get("kind")
    if kind == "scale_values":
        values = version.get("values")
        if values is None:
            raise OverrideError(f"parameter {rule.get('name')} has no values to scale")
        m = _finite_number(patch.get("multiplier"), "multiplier")
        for k in list(values.keys()):
            values[k] = round(values[k] * m)
    elif kind == "set_values":
        new_values = patch.get("values")
        if not isinstance(new_values, dict):
            raise OverrideError("set_values needs a values object")
        values = version.setdefault("values", {})
        for k, v in new_values.items():
            _finite_number(v, f"values[{k!r}]")
            values[k] = v  # as given, so 300 stays 300 in the YAML
    elif kind == "scale_formula":
        formula = version.get("formula")
        if formula is None:
            raise OverrideError(f"parameter {rule.get('name')} has no formula")
        try:
            n = float(formula)
        except (TypeError, ValueError):
            raise OverrideError(
                f"scale_formula only supports numeric-literal formulas; "
                f"{rule.get('name')} = {formula!r}"
            )
        m = _finite_number(patch.get("multiplier"), "multiplier")
        version["formula"] = f"{round(n * m * 100) / 100}"
    elif kind == "set_formula":
        formula = patch.get("formula")
        if not isinstance(formula, str):
            raise OverrideError("set_formula needs a formula string")
        version["formula"] = formula
    else:
        raise OverrideError(f"unknown patch kind: {kind!r}")


def _digest(material: Any) -> str:
    return hashlib.sha256(
        json.dumps(material, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


@dataclass
class ProgramTree:
    """One program's rulespec pair on disk, patched in place under ``lock``.

    Invariant: outside ``compile_locked`` every file holds its original
    bytes. ``compile_locked`` restores them before it returns or raises; if a
    restore ever fails to read back identical bytes, the tree is marked
    unavailable and refuses further override compiles (HTTP 503) rather
    than compile against a tree it can no longer vouch for.
    """

    slug: str
    root: Path
    state_repo: str
    program_rel: str
    lock: threading.Lock = field(default_factory=threading.Lock)
    # ruamel YAML instances keep parser state and are not thread-safe; each
    # tree owns one and uses it only under ``lock``.
    yaml_io: Any = field(default_factory=make_yaml)
    unavailable: str | None = None

    @property
    def program_yaml(self) -> Path:
        return self.root / self.state_repo / self.program_rel

    def resolve_target(self, override: Any) -> Path:
        """Validate one override and return the file it patches."""
        if not isinstance(override, dict):
            raise OverrideError(f"override must be an object, got {override!r}")
        repo = override.get("repo")
        canonical = REPO_CANONICAL.get(repo) if isinstance(repo, str) else None
        if canonical is None:
            raise OverrideError(f"unknown override repo: {repo!r}")
        allowed = {"rulespec-us", self.state_repo}
        if canonical not in allowed:
            raise OverrideError(
                f"override repo {repo!r} is not valid for program {self.slug!r} "
                f"(allowed: {sorted(allowed)})"
            )
        rel = override.get("file_relative")
        if not isinstance(rel, str) or not rel.endswith((".yaml", ".yml")):
            raise OverrideError(f"file_relative must be a .yaml path, got {rel!r}")
        repo_root = (self.root / canonical).resolve()
        target = (repo_root / rel).resolve()
        if not target.is_relative_to(repo_root):
            raise OverrideError(f"file_relative escapes {canonical}: {rel!r}")
        if not target.is_file():
            raise OverrideError(f"override target not found: {canonical}/{rel}")
        if not isinstance(override.get("parameter"), str):
            raise OverrideError("override parameter must be a string")
        return target

    def compile_locked(self, bin_path: str, overrides: list[Any], output: Path) -> None:
        """Patch, compile to ``output``, restore. Caller holds ``self.lock``."""
        if self.unavailable:
            raise TreeUnavailable(self.unavailable)

        # 1. Validate and patch in memory. Nothing touches disk until every
        #    override has resolved, so a bad request leaves the tree as is.
        by_file: dict[Path, list[dict[str, Any]]] = {}
        for ov in overrides:
            by_file.setdefault(self.resolve_target(ov), []).append(ov)
        originals: dict[Path, bytes] = {}
        patched: dict[Path, str] = {}
        for file, file_overrides in by_file.items():
            original = file.read_bytes()
            doc = self.yaml_io.load(original.decode("utf-8"))
            rel = file.relative_to(self.root.resolve())
            if not isinstance(doc, dict) or not isinstance(doc.get("rules"), list):
                raise OverrideError(f"no rules array in {rel}")
            for ov in file_overrides:
                rule = next(
                    (
                        r
                        for r in doc["rules"]
                        if isinstance(r, dict) and r.get("name") == ov["parameter"]
                    ),
                    None,
                )
                if rule is None:
                    raise OverrideError(f"parameter {ov['parameter']} not found in {rel}")
                if rule.get("kind") != "parameter":
                    raise OverrideError(
                        f"rule {ov['parameter']} in {rel} is kind={rule.get('kind')}, "
                        "not parameter"
                    )
                apply_patch(rule, ov.get("patch"))
            buf = io.StringIO()
            self.yaml_io.dump(doc, buf)
            originals[file] = original
            patched[file] = buf.getvalue()

        # 2. Write, compile, restore.
        try:
            for file, text in patched.items():
                file.write_text(text, encoding="utf-8")
            try:
                proc = subprocess.run(
                    [bin_path, "compile", "--program", str(self.program_yaml), "--output", str(output)],
                    text=True,
                    capture_output=True,
                    timeout=COMPILE_TIMEOUT_S,
                )
            except subprocess.TimeoutExpired:
                raise EngineError(f"compile timed out after {COMPILE_TIMEOUT_S}s")
            if proc.returncode != 0:
                raise EngineError(f"compile failed ({proc.returncode}): {proc.stderr.strip()}")
        finally:
            self._restore(originals)

    def _restore(self, originals: dict[Path, bytes]) -> None:
        for file, data in originals.items():
            try:
                file.write_bytes(data)
                ok = file.read_bytes() == data
            except OSError:
                ok = False
            if not ok:
                self.unavailable = f"{file} could not be restored after an override compile"
                log.error(self.unavailable)


class CompiledCache:
    """LRU of compiled override artifacts on local disk, keyed by a digest
    of (program, overrides). Evicting an entry deletes its file."""

    def __init__(self, directory: Path, max_entries: int):
        self.dir = directory
        self.max = max(1, max_entries)
        self._entries: OrderedDict[str, Path] = OrderedDict()
        self._lock = threading.Lock()

    def path_for(self, key: str) -> Path:
        return self.dir / f"{key}.compiled.json"

    def get(self, key: str) -> Path | None:
        with self._lock:
            path = self._entries.get(key)
            if path is None:
                return None
            if not path.exists():
                # The file is gone; forget the entry so the caller compiles
                # again rather than handing out a dead path forever.
                del self._entries[key]
                return None
            self._entries.move_to_end(key)
            return path

    def put(self, key: str, path: Path) -> None:
        # Evicted files are unlinked under the lock, so an eviction can't
        # land after a concurrent recompile of the same key and delete it.
        with self._lock:
            self._entries[key] = path
            self._entries.move_to_end(key)
            while len(self._entries) > self.max:
                self._entries.popitem(last=False)[1].unlink(missing_ok=True)


class ResultCache:
    """Thread-safe in-memory LRU of JSON results. Per container; survives
    as long as Modal keeps the container warm. 256 entries × ~5 KB is
    ~1.3 MB. Slider drags that revisit a configuration return with no
    engine call."""

    def __init__(self, max_entries: int):
        self.max = max(1, max_entries)
        self._entries: OrderedDict[str, dict[str, Any]] = OrderedDict()
        self._lock = threading.Lock()

    def get(self, key: str) -> dict[str, Any] | None:
        with self._lock:
            hit = self._entries.get(key)
            if hit is not None:
                self._entries.move_to_end(key)
            return hit

    def put(self, key: str, value: dict[str, Any]) -> None:
        with self._lock:
            self._entries[key] = value
            self._entries.move_to_end(key)
            while len(self._entries) > self.max:
                self._entries.popitem(last=False)


