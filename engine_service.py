def _coerce(value: Any, cast: Any, what: str) -> Any:
    """``cast(value)``, with every failure (wrong type, non-numeric string,
    overflow, NaN or infinity) raised as a 400 rather than a 500."""
    try:
        out = cast(value)
    except (TypeError, ValueError, OverflowError):
        raise OverrideError(f"{what} must be a number, got {value!r}")
    if isinstance(out, float) and not math.isfinite(out):
        raise OverrideError(f"{what} must be finite, got {value!r}")
    return out


class EngineService:
    def __init__(self, config: ServiceConfig):
        self.config = config
        self.bin = config.bin_path
        self.artifacts = {
            slug: config.artifacts_dir / f"{slug}.compiled.json" for slug in config.programs
        }
        self.bases: dict[str, dict[str, Any]] = {}
        for slug in config.programs:
            with open(config.bases_dir / f"{slug}-base.json") as f:
                self.bases[slug] = json.load(f)
        self.program_config = program_config(self.bases)
        self.trees = {
            slug: ProgramTree(
                slug=slug,
                root=config.programs_root / slug,
                state_repo=cfg["state_repo"],
                program_rel=cfg["program_rel"],
            )
            for slug, cfg in config.programs.items()
        }
        scratch = config.scratch_dir or Path(tempfile.mkdtemp(prefix="co-snap-compiled-"))
        scratch.mkdir(parents=True, exist_ok=True)
        self.scratch = scratch
        self.compiled = CompiledCache(scratch, config.compiled_cache_max)
        self.results = ResultCache(config.result_cache_max)
        self.prewarm_status: dict[str, dict[str, Any]] = {
            slug: {"state": "pending" if config.prewarm else "skipped"} for slug in config.programs
        }

    # -- engine ------------------------------------------------------------

    def run_compiled(self, artifact: Path, request_json: str) -> dict[str, Any]:
        try:
            proc = subprocess.run(
                [self.bin, "run-compiled", "--artifact", str(artifact)],
                input=request_json,
                text=True,
                capture_output=True,
                timeout=RUN_TIMEOUT_S,
            )
        except subprocess.TimeoutExpired:
            raise EngineError(f"axiom-rules-engine timed out after {RUN_TIMEOUT_S}s")
        if proc.returncode != 0:
            raise EngineError(f"axiom-rules-engine exited {proc.returncode}: {proc.stderr.strip()}")
        try:
            return json.loads(proc.stdout)
        except json.JSONDecodeError as err:
            raise EngineError(f"could not parse engine output: {err}")

    def compiled_artifact(self, slug: str, overrides: list[Any]) -> tuple[Path, bool]:
        """Artifact for (slug, overrides) and whether it was compiled fresh."""
        if not overrides:
            return self.artifacts[slug], False
        key = _digest({"p": slug, "o": overrides})
        hit = self.compiled.get(key)
        if hit is not None:
            return hit, False
        tree = self.trees[slug]
        with tree.lock:
            # Another request may have compiled the same reform while this
            # one waited on the lock.
            hit = self.compiled.get(key)
            if hit is not None:
                return hit, False
            out = self.compiled.path_for(key)
            # Compile beside the final path and rename into place, so a run
            # never opens a half-written artifact.
            tmp = out.with_name(f"{out.name}.{threading.get_ident()}.tmp")
            try:
                tree.compile_locked(self.bin, overrides, tmp)
                os.replace(tmp, out)
            finally:
                tmp.unlink(missing_ok=True)
            self.compiled.put(key, out)
            return out, True

    def execute(self, slug: str, overrides: list[Any], engine_request: dict) -> dict[str, Any]:
        t0 = time.monotonic()
        artifact, fresh = self.compiled_artifact(slug, overrides)
        t1 = time.monotonic()
        request_json = json.dumps(engine_request)
        try:
            result = self.run_compiled(artifact, request_json)
        except EngineError:
            if artifact.exists():
                raise
            # Evicted between lookup and spawn: the lookup below finds the
            # entry gone (or heals it) and compiles again. Retry once.
            artifact, fresh = self.compiled_artifact(slug, overrides)
            result = self.run_compiled(artifact, request_json)
        log.info(
            "engine program=%s overrides=%d artifact=%s compile_ms=%d run_ms=%d",
            slug,
            len(overrides),
            "compiled" if fresh else ("cached" if overrides else "prebuilt"),
            (t1 - t0) * 1000,
            (time.monotonic() - t1) * 1000,
        )
        return result

    # -- endpoints -----------------------------------------------------------

    def _program(self, body: dict) -> str:
        program = body.get("program") or self.config.default_program
        if program not in self.artifacts:
            raise OverrideError(f"unknown program: {program!r}; known: {list(self.artifacts)}")
        return program

    @staticmethod
    def _overrides(body: dict) -> list[Any]:
        overrides = body.get("overrides") or []
        if not isinstance(overrides, list):
            raise OverrideError("overrides must be a list")
        return overrides

    def run(self, body: dict) -> dict[str, Any]:
        program = self._program(body)
        overrides = self._overrides(body)
        engine_request = body.get("request")
        if not isinstance(engine_request, dict):
            raise OverrideError("missing or invalid `request` body")
        key = _digest({"p": program, "r": engine_request, "o": overrides})
        hit = self.results.get(key)
        if hit is not None:
            return hit
        result = self.execute(program, overrides, engine_request)
        self.results.put(key, result)
        return result

    def cliff_sweep(self, body: dict) -> dict[str, Any]:
        """Thin-payload endpoint. Takes ~150 bytes instead of ~100 KB, builds
        the engine request server-side, runs the engine (with overrides if
        supplied), computes MTR + cliff metrics, and returns the SweepResult
        that lib/cliffs.ts used to assemble on Vercel."""
        program = self._program(body)
        overrides = self._overrides(body)
        household = body.get("household") or {}
        if not isinstance(household, dict):
            raise OverrideError("household must be an object")
        # Same defaulting as the pre-fix service (a falsy value means the
        # default), so direct API callers see unchanged results; what's new
        # is that bad values answer 400 and the work is bounded.
        size = max(1, _coerce(household.get("household_size") or 1, int, "household_size"))
        if size > MAX_HOUSEHOLD_SIZE:
            raise OverrideError(f"household_size must be at most {MAX_HOUSEHOLD_SIZE}, got {size}")
        earnings_min = _coerce(body.get("earnings_min") or 0, int, "earnings_min")
        earnings_max = _coerce(body.get("earnings_max") or 4000, int, "earnings_max")
        earnings_step = _coerce(body.get("earnings_step") or 100, int, "earnings_step")
        cliff_threshold = _coerce(body.get("cliff_mtr_threshold") or 1.0, float, "cliff_mtr_threshold")
        if earnings_step < 1:
            raise OverrideError("earnings_step must be >= 1")
        # Check the length before materializing: len(range) is O(1), but
        # raises OverflowError past sys.maxsize.
        points_range = range(earnings_min, earnings_max + 1, earnings_step)
        try:
            n_points = len(points_range)
        except OverflowError:
            n_points = MAX_SWEEP_POINTS + 1
        if n_points > MAX_SWEEP_POINTS:
            raise OverrideError(f"the sweep may have at most {MAX_SWEEP_POINTS} points")
        earnings_points = list(points_range)

        # Cache on the thin-payload shape so two clients with identical
        # sliders get the same cached result.
        key = "sweep:" + _digest(
            {
                "program": program,
                "household": household,
                "range": [earnings_min, earnings_max, earnings_step],
                "overrides": overrides,
                "threshold": cliff_threshold,
            }
        )
        hit = self.results.get(key)
        if hit is not None:
            return hit

        try:
            engine_request, _period = build_sweep_request(
                self.program_config[program], self.bases[program], household, earnings_points
            )
        except (TypeError, ValueError, OverflowError) as err:
            raise OverrideError(f"invalid household facts: {err}")
        start = time.monotonic()
        engine_response = self.execute(program, overrides, engine_request)
        result = make_sweep_result(
            self.bases[program], engine_response, earnings_points, cliff_threshold
        )
        result["ms"] = int((time.monotonic() - start) * 1000)
        self.results.put(key, result)
        return result

    def health(self) -> dict[str, Any]:
        return {
            "ok": Path(self.bin).exists() and not any(t.unavailable for t in self.trees.values()),
            "binary": self.bin,
            "programs": {
                slug: {
                    "artifact": str(path),
                    "exists": path.exists(),
                    "prewarm": self.prewarm_status[slug],
                    **({"unavailable": self.trees[slug].unavailable} if self.trees[slug].unavailable else {}),
                }
                for slug, path in self.artifacts.items()
            },
            "default_program": self.config.default_program,
            "engine_version": self.config.engine_version,
        }

    # -- prewarm -------------------------------------------------------------

    def prewarm(self) -> None:
        """Compile each program once with no overrides. Reads its import
        closure into the page cache and checks the in-place tree still
        compiles to the baked artifact ("mismatch" means it drifted)."""
        order = sorted(self.trees, key=lambda s: s != self.config.default_program)
        for slug in order:
            tree = self.trees[slug]
            out = self.scratch / f"prewarm-{slug}.compiled.json"
            t0 = time.monotonic()
            try:
                with tree.lock:
                    tree.compile_locked(self.bin, [], out)
                same = out.read_bytes() == self.artifacts[slug].read_bytes()
                status = {
                    "state": "ok" if same else "mismatch",
                    "ms": int((time.monotonic() - t0) * 1000),
                }
            except Exception as err:  # noqa: BLE001 — report, never crash the container
                status = {"state": "error", "detail": str(err)[:300]}
            finally:
                out.unlink(missing_ok=True)
            self.prewarm_status[slug] = status
            log.info("prewarm program=%s %s", slug, status)

    def start_prewarm(self) -> threading.Thread:
        thread = threading.Thread(target=self.prewarm, name="prewarm", daemon=True)
        thread.start()
        return thread


def create_app(config: ServiceConfig) -> "FastAPI":
    """FastAPI app for the service.

    POST /run         {program, request, overrides?}  → ExecutionResponse
    POST /cliff-sweep {program?, household, ...}      → SweepResult
    GET  /health      → {ok, programs, engine_version}
    """
    from contextlib import contextmanager

    from fastapi import Body, FastAPI, HTTPException
    from fastapi.middleware.cors import CORSMiddleware

    if not logging.getLogger().handlers:
        logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s %(message)s")
    log.setLevel(logging.INFO)

    service = EngineService(config)
    api = FastAPI(title="co-snap-cliffs engine", version="0.3.0")
    api.state.service = service
    api.add_middleware(
        CORSMiddleware,
        allow_origins=["*"],
        allow_methods=["GET", "POST", "OPTIONS"],
        allow_headers=["*"],
    )

    @contextmanager
    def http_errors():
        try:
            yield
        except OverrideError as err:
            raise HTTPException(400, str(err))
        except TreeUnavailable as err:
            raise HTTPException(503, str(err))
        except EngineError as err:
            raise HTTPException(500, str(err))

    @api.get("/health")
    def health():
        return service.health()

    @api.post("/run")
    def run(body: dict[str, Any] = Body(...)):
        with http_errors():
            return service.run(body)

    @api.post("/cliff-sweep")
    def cliff_sweep(body: dict[str, Any] = Body(...)):
        with http_errors():
            return service.cliff_sweep(body)

    if config.prewarm:
        service.start_prewarm()
    return api
